#!/usr/bin/env node
/**
 * Deck use-case generator: the event emulator's library (services/event-emulator/src/event_emulator/
 * use_case_library.json) becomes src/lib/ops/usecases.generated.ts, the rows src/lib/ops/usecases.ts builds the
 * board's preview fixtures, the twin's scenario picker and the emulator panel's launch presets from. The deck never
 * writes a scenario of its own: ids, names, spines, departures, policies, seeds, horizons and descriptions are the
 * library's, so a new city's library is one regenerated module (tests/contract/run.mjs §10 holds the spines equal).
 *
 *   node scripts/gen_deck_usecases.mjs           write the module
 *   node scripts/gen_deck_usecases.mjs --check   exit 1 when the committed module differs from the library
 *   node scripts/gen_deck_usecases.mjs --stdout  print the module instead of writing it
 *
 * Which rows: the deck's chosen ids (DECK_IDS: the seeded event profiles and the city-feeds scenarios) when the library
 * holds them, else every scenario of the library (a city whose library the deck has not curated yet). The crowd class
 * is the library's (its MEDIUM is the deck's MODERATE) unless DECK_CROWD names the showcase's own mapping.
 * Deterministic (no timestamps): --check compares bytes.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DECK = path.resolve(HERE, '..');
const LIB = path.resolve(DECK, '..', 'event-emulator', 'src', 'event_emulator', 'use_case_library.json');
const OUT = path.join(DECK, 'src', 'lib', 'ops', 'usecases.generated.ts');
const argv = process.argv.slice(2);

/** The deck's curated board: the seeded event profiles (migration 008) and the city-feeds scenarios, in board order. */
const DECK_IDS = [
	// Kolkata's library
	'vvip_convoy_base',
	'ganesh_visarjan_girgaon',
	'gateway_ferry_transit',
	'mumbai_marathon',
	'shivaji_park_parade',
	'wankhede_egress',
	'cloudburst_high_tide',
	'metro_work_zone',
	'crawford_market_fire',
	'mithi_overflow_kurla',
	'diwali_air_quality',
	'october_heat_breakdowns',
	'weh_treefall_squall',
];

/** The showcase's crowd mapping where it differs from the library's own class. */
const DECK_CROWD = {
	cloudburst_high_tide: 'HIGH',
	metro_work_zone: 'MODERATE',
	mithi_overflow_kurla: 'MODERATE',
};

const CROWD = { LOW: 'LOW', MEDIUM: 'MODERATE', MODERATE: 'MODERATE', HIGH: 'HIGH', EXTREME: 'EXTREME' };
const PROTECTION = new Set(['Z+', 'Z', 'Y', 'X', 'none']);

function fail(msg) {
	console.error(`gen_deck_usecases: ${msg}`);
	process.exit(2);
}

let lib;
try {
	lib = JSON.parse(readFileSync(LIB, 'utf8'));
} catch (e) {
	fail(`cannot read ${path.relative(DECK, LIB)}: ${e.message}`);
}
if (!Array.isArray(lib) || !lib.length) fail('the library is empty');
const byId = new Map(lib.map((u) => [u.id, u]));
const curated = DECK_IDS.filter((id) => byId.has(id));
const ids = curated.length ? curated : lib.map((u) => u.id);

const rows = ids.map((id) => {
	const c = byId.get(id).scenarioConfig ?? fail(`${id}: no scenarioConfig`);
	const crowd = DECK_CROWD[id] ?? CROWD[String(c.crowd_class ?? 'LOW').toUpperCase()] ?? fail(`${id}: crowd class ${c.crowd_class}`);
	const protection = PROTECTION.has(c.vvip_class) ? c.vvip_class : fail(`${id}: protection class ${c.vvip_class}`);
	if (!Array.isArray(c.route_segment_ids) || !c.route_segment_ids.length) fail(`${id}: no route spine`);
	if (!/[+-]\d{2}:\d{2}$/.test(String(c.departure_time))) fail(`${id}: departure ${c.departure_time} carries no offset`);
	return {
		id,
		scenarioId: c.scenario_id ?? id,
		name: c.name,
		eventKind: c.event_kind,
		protectionClass: protection,
		crowdClass: crowd,
		routeSegmentIds: c.route_segment_ids,
		departureTime: c.departure_time,
		baselinePolicy: { advanceClosureSec: c.closure_policy?.advance_closure_sec ?? null, closureType: c.closure_policy?.closure_type ?? 'signal_hold' },
		seed: c.seed,
		nReplications: c.n_replications,
		horizonMin: c.horizon_min,
		description: c.description,
	};
});

const body = `/**
 * GENERATED by scripts/gen_deck_usecases.mjs from services/event-emulator/src/event_emulator/use_case_library.json
 * (${rows.length} of the library's ${lib.length} scenarios${curated.length ? ', the deck\'s curated board' : ', the whole library'}). Do not edit: change the library (or the
 * generator's DECK_IDS) and run \`node scripts/gen_deck_usecases.mjs\`. Read it through $lib/ops/usecases.
 */

export const USE_CASE_ROWS = ${JSON.stringify(rows, null, '\t')} as const;
`;

if (argv.includes('--stdout')) process.stdout.write(body);
else if (argv.includes('--check')) {
	let cur = '';
	try {
		cur = readFileSync(OUT, 'utf8');
	} catch {
		/* missing */
	}
	if (cur !== body) {
		console.error('gen_deck_usecases: usecases.generated.ts is stale — run node scripts/gen_deck_usecases.mjs');
		process.exit(1);
	}
	console.log('gen_deck_usecases: up to date');
} else {
	writeFileSync(OUT, body);
	console.log(`gen_deck_usecases: wrote ${path.relative(DECK, OUT)} (${rows.length} use cases)`);
}
